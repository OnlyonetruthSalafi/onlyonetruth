// ── แปลงข้อความเป็นคำอ่านสำหรับ TTS ─────────────────────────────────
const DIGITS = ["ศูนย์", "หนึ่ง", "สอง", "สาม", "สี่", "ห้า", "หก", "เจ็ด", "แปด", "เก้า"];
const PLACES = ["", "สิบ", "ร้อย", "พัน", "หมื่น", "แสน"];

/** จำนวนเต็ม 0..999999 → คำอ่านไทย (เช่น 711 → เจ็ดร้อยสิบเอ็ด) */
export function thaiNumber(n) {
  if (n === 0) return DIGITS[0];
  const s = String(n);
  let out = "";
  for (let i = 0; i < s.length; i++) {
    const d = Number(s[i]);
    const place = s.length - 1 - i;
    if (d === 0) continue;
    if (place === 1 && d === 1) out += "สิบ";
    else if (place === 1 && d === 2) out += "ยี่สิบ";
    else if (place === 0 && d === 1 && s.length > 1) out += "เอ็ด";
    else out += DIGITS[d] + PLACES[place];
  }
  return out;
}

/** ข้อความบทพากย์ → ข้อความคำอ่าน (ขยายคำย่อ ตัวเลข ช่วงปี) */
export function toSpeech(text) {
  return text
    .replace(/\(ซ\.ล\.\)/g, "ศ็อลลัลลอฮุอะลัยฮิวะซัลลัม")
    .replace(/ปีก่อน ค\.ศ\./g, "ปีก่อนคริสต์ศักราช")
    .replace(/ค\.ศ\.\s*/g, "คริสต์ศักราช ")
    .replace(/~\s*/g, "ราว")
    .replace(/(\d+)\s*[–-]\s*(\d+)/g, "$1 ถึง $2")
    .replace(/\d+/g, (m) => thaiNumber(Number(m)))
    .replace(/\s{2,}/g, " ")
    .trim();
}
